// Generate `config.js` for the static admin panel from `.env`.
//
// A browser cannot read `.env`, so the non-secret base URL is written into a
// small JS file the page loads before `admin.js`. Anything written here is
// public — never put the admin secret in this file.
//
// Usage: npm run config   (or: npm run config -- --out path/to/config.js)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function readEnv(file) {
  const values = {}
  let text = ''
  try {
    text = readFileSync(file, 'utf8')
  } catch {
    return values
  }
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) continue
    const eq = line.indexOf('=')
    if (eq === -1) continue
    const key = line.slice(0, eq).trim()
    let value = line.slice(eq + 1).trim()
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1)
    }
    values[key] = value
  }
  return values
}

const env = { ...readEnv(join(root, '.env')), ...process.env }

const hubUrl = (env.HUB_URL || '').trim().replace(/\/+$/, '')
if (!hubUrl) {
  console.error('[gen-admin-config] HUB_URL is not set in .env — refusing to write a blank config.')
  process.exit(1)
}
if (!/^https?:\/\//.test(hubUrl)) {
  console.error(`[gen-admin-config] HUB_URL must be an http(s) URL, got: ${hubUrl}`)
  process.exit(1)
}

const outIndex = process.argv.indexOf('--out')
const outPath = outIndex !== -1 && process.argv[outIndex + 1]
  ? resolve(process.cwd(), process.argv[outIndex + 1])
  : join(root, 'config.js')

// ASCII only: this file is served to a browser, and avoiding non-ASCII sidesteps
// any charset mismatch between the file and the page that loads it.
const banner = '// AUTO-GENERATED by scripts/gen-admin-config.mjs - do not edit or commit.'
const contents =
  `${banner}\n` +
  '// Contains no secrets: the admin secret is entered by the operator at runtime.\n' +
  `window.VOLUMPOS_HUB = Object.freeze({\n  baseUrl: ${JSON.stringify(hubUrl)}\n})\n`

writeFileSync(outPath, contents, 'utf8')
console.log(`[gen-admin-config] wrote ${outPath}`)
console.log(`[gen-admin-config] baseUrl = ${hubUrl}`)
